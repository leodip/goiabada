#!/bin/sh
# Writes .env beside this script, once: the dev stack's data key and its three database passwords,
# drawn fresh for this checkout, so no file in the repository supplies one by literal (#501).
# Compose reads .env from this directory when it interpolates docker-compose.yml, which hands the
# values to the databases and to the devcontainer alike. devcontainer.json runs this as its
# initializeCommand, and .placido/stack.sh before every `up`.
#
# An existing .env is kept: MySQL, PostgreSQL and SQL Server each keep the password their volume
# was initialised with, and a dev database is sealed under the key it was seeded with. Delete it
# only together with the stack's volumes. .gitignore keeps it out of the repository.
set -eu

env_file="$(cd "$(dirname "$0")" && pwd)/.env"
[ -f "$env_file" ] && exit 0

# od rather than openssl: every host that runs Compose has it.
hex() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }

# SQL Server's policy asks for three of upper case, lower case, digits and symbols, which a hex
# string lacks.
mssql_password="Aa1-$(hex 24)"

umask 077
tmp="$env_file.$$"
{
    echo "# Generated by generate-env.sh for this checkout's dev stack (#501). Never commit it."
    echo "GOIABADA_AES_ENCRYPTION_KEY=$(hex 32)"
    echo "MYSQL_ROOT_PASSWORD=$(hex 24)"
    echo "POSTGRES_PASSWORD=$(hex 24)"
    echo "MSSQL_SA_PASSWORD=$mssql_password"
} >"$tmp"
mv "$tmp" "$env_file"
echo "generate-env.sh: wrote $env_file"
