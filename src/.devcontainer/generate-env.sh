#!/bin/sh
# Writes .env beside this script: the dev stack's data key and its three database passwords,
# drawn fresh for this checkout, so no file in the repository supplies one by literal (#501).
# Compose reads .env from this directory when it interpolates docker-compose.yml, which hands the
# values to the databases and to the devcontainer alike. devcontainer.json runs this as its
# initializeCommand, and .placido/stack.sh before every `up`.
#
# An existing .env keeps every value it holds: MySQL, PostgreSQL and SQL Server each keep the
# password their volume was initialised with, and a dev database is sealed under the key it was
# seeded with. A variable it lacks, or holds empty, is drawn and added, so a .env written by hand
# for USER_UID and USER_GID, which Compose also reads from it, gains the four rather than being
# left without them. It reads an assignment as Compose does, `export NAME=value` and
# `NAME = value` included, and `NAME=""` as empty. Whatever it held, it is left readable by its
# owner alone. Delete the file only together with the stack's volumes. .gitignore keeps it out of
# the repository.
set -eu

env_file="$(cd "$(dirname "$0")" && pwd)/.env"
names="GOIABADA_AES_ENCRYPTION_KEY MYSQL_ROOT_PASSWORD POSTGRES_PASSWORD MSSQL_SA_PASSWORD"

# od rather than openssl: every host that runs Compose has it.
hex() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }

value_for() {
    case "$1" in
        GOIABADA_AES_ENCRYPTION_KEY) hex 32 ;;
        # SQL Server's policy asks for three of upper case, lower case, digits and symbols, which
        # a hex string lacks.
        MSSQL_SA_PASSWORD) echo "Aa1-$(hex 24)" ;;
        *) hex 24 ;;
    esac
}

# An assignment of one of names as Compose reads it: perhaps exported, perhaps spaced around the `=`.
assignment() { echo "^[[:space:]]*(export[[:space:]]+)?($1)[[:space:]]*="; }
# One Compose reads as empty: nothing, or an empty pair of quotes, before perhaps a comment and the
# line's end, a CR among the spaces there.
empty_assignment() { echo "$(assignment "$1")[[:space:]]*(\"\"|'')?([[:space:]]+#.*)?[[:space:]]*\$"; }

umask 077
tmp="$env_file.$$"
if [ -f "$env_file" ]; then
    empty="$(empty_assignment "$(echo $names | tr ' ' '|')")"
    # Every line but an empty assignment of one of the four, which Compose would read as no value,
    # or as overriding the one before it.
    grep -v -E "$empty" "$env_file" >"$tmp" || true
    missing=""
    for name in $names; do
        grep -q -E "$(assignment "$name")" "$tmp" || missing="$missing $name"
    done
    if [ -z "$missing" ] && ! grep -q -E "$empty" "$env_file"; then
        # Complete: its contents stay as they are, but not a mode that lets others read it.
        rm -f "$tmp"
        chmod 600 "$env_file"
        exit 0
    fi
else
    missing="$names"
    echo "# Generated by generate-env.sh for this checkout's dev stack (#501). Never commit it." >"$tmp"
fi
for name in $missing; do
    echo "$name=$(value_for "$name")" >>"$tmp"
done
# The new file is written under umask 077, so the .env it replaces is left at 0600 whatever its
# mode was.
mv "$tmp" "$env_file"
echo "generate-env.sh: wrote$(echo "${missing:- no new value}" | sed 's/^ */ /') to $env_file"
