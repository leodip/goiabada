-- A public client always requires PKCE (#245). See the sqlite migration of the
-- same number for why the column is migrated at all when the model rule already
-- answers `required`, and why the predicate is is_public rather than
-- pkce_required = false.
--
-- is_public is BIT here, so the literal is 1.
--
-- No EXEC wrapper, unlike 000029. That file needs one because SQL Server
-- compiles an entire batch before executing any of it, so an UPDATE naming a
-- column the same batch has just added fails at compile time. This migration
-- adds no column and names only columns that already exist, so a plain
-- statement resolves.
UPDATE [clients] SET [pkce_required] = 1 WHERE [is_public] = 1;
