	sb.WriteString("              key: admin-session-auth-key\n")
	sb.WriteString("        - name: GOIABADA_ADMINCONSOLE_SESSION_ENCRYPTION_KEY\n")
	sb.WriteString("          valueFrom:\n")
	sb.WriteString("            secretKeyRef:\n")
	sb.WriteString("              name: goiabada-secrets\n")
	sb.WriteString("              key: admin-session-enc-key\n")
	writeProbes(&sb, 9091,
		"The auth server's budget: this server starts in seconds.")
	writePreStopPause(&sb)
	writeResources(&sb,
		"The auth server's numbers. This server verifies no passwords and needs less.")
	sb.WriteString("\n")
	writeDisruptionBudget(&sb, ns, "goiabada-adminconsole")
