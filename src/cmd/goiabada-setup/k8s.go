	sb.WriteString("          requests:\n")
	sb.WriteString("            memory: \"128Mi\"\n")
	sb.WriteString("            cpu: \"100m\"\n")
	sb.WriteString("          limits:\n")
	sb.WriteString("            memory: \"512Mi\"\n")
	sb.WriteString("            cpu: \"500m\"\n")
	sb.WriteString("\n")

