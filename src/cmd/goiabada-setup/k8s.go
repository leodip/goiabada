	fmt.Fprintf(&sb, "  namespace: %s\n", yamlQuote(ns))
	sb.WriteString("spec:\n")
	sb.WriteString("  selector:\n")
	sb.WriteString("    app: goiabada-adminconsole\n")
	sb.WriteString("  ports:\n")
	sb.WriteString("  - port: 9091\n")
